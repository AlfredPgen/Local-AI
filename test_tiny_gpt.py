class CharTok:
    """A tiny stand-in tokenizer for model-level tests."""
    bos_id, eos_id = 0, -1

    def encode(self, text):
        return [1 + ord(c) % 40 for c in text]

    def decode(self, ids):
        return "".join(chr(64 + i % 60) for i in ids)


